// Samples the geoid undulation (WGS84 ellipsoid height minus Swiss sea-level height) on a regular
// grid over Switzerland and writes src/geo/geoidGrid.ts. swisstopo's terrain tiles carry heights
// above sea level; the game works with heights above the ellipsoid, so the world adds this.
//
// Uses swisstopo's REFRAME service in two steps per grid point: LHN95 (sea level) -> ellipsoidal
// height on the Bessel ellipsoid (CHGeo2004 geoid), then LV95/Bessel -> WGS84. Outside
// Switzerland CHGeo2004 is not defined; those points take the Bessel geoid value of the nearest
// defined point (the geoid changes slowly) plus the exact datum shift.
//
// Run: node tools/world/geoid.mjs  (about 600 requests, a minute or two)
import { writeFileSync } from 'node:fs';

const WEST = 5.5;
const SOUTH = 45.5;
const STEP = 0.25;
const COLS = 23; // 5.5 .. 11.0
const ROWS = 12; // 45.5 .. 48.25
const H = 1000;
const API = 'https://geodesy.geo.admin.ch/reframe/';

/** swisstopo's approximate WGS84 -> LV95 formulas (a few metres, plenty for a geoid lookup). */
function toLv95(lon, lat) {
  const p = (lat * 3600 - 169_028.66) / 10_000;
  const l = (lon * 3600 - 26_782.5) / 10_000;
  return {
    e: 2_600_072.37 + 211_455.93 * l - 10_938.51 * l * p - 0.36 * l * p * p - 44.54 * l ** 3,
    n:
      1_200_147.07 +
      308_807.95 * p +
      3_745.25 * l * l +
      76.63 * p * p -
      194.56 * l * l * p +
      119.79 * p ** 3,
  };
}

async function get(path, e, n, h) {
  for (let attempt = 0; ; attempt++) {
    try {
      const res = await fetch(`${API}${path}?easting=${e}&northing=${n}&altitude=${h}&format=json`);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      return json.altitude === undefined ? undefined : Number(json.altitude);
    } catch (err) {
      if (attempt >= 3) throw err;
      await new Promise((r) => setTimeout(r, 500 * 2 ** attempt));
    }
  }
}

const points = [];
for (let r = 0; r < ROWS; r++)
  for (let c = 0; c < COLS; c++) points.push({ r, c, lon: WEST + c * STEP, lat: SOUTH + r * STEP });

let next = 0;
await Promise.all(
  Array.from({ length: 6 }, async () => {
    while (next < points.length) {
      const p = points[next++];
      const { e, n } = toLv95(p.lon, p.lat);
      // Bessel ellipsoidal height of a point 1000 m above sea level (undefined outside CH).
      p.bessel = await get('lhn95tobessel', e.toFixed(2), n.toFixed(2), H);
      // Datum shift Bessel -> WGS84 for a point at Bessel height H.
      p.shift = (await get('lv95towgs84', e.toFixed(2), n.toFixed(2), H)) - H;
    }
  }),
);

for (const p of points) {
  if (p.bessel !== undefined) {
    p.besselGeoid = p.bessel - H;
    continue;
  }
  let best;
  let bestD = Infinity;
  for (const q of points) {
    if (q.bessel === undefined) continue;
    const d = Math.hypot((q.lon - p.lon) * Math.cos((p.lat * Math.PI) / 180), q.lat - p.lat);
    if (d < bestD) {
      bestD = d;
      best = q;
    }
  }
  p.besselGeoid = best.bessel - H;
}

const values = points.map((p) => (p.besselGeoid + p.shift).toFixed(2));
const rows = [];
for (let r = 0; r < ROWS; r++)
  rows.push('  ' + values.slice(r * COLS, (r + 1) * COLS).join(', ') + ',');

const out = `// Generated by tools/world/geoid.mjs from swisstopo REFRAME (CHGeo2004 + LV95 -> WGS84).
// Do not edit by hand.

/** Geoid undulation N (WGS84 ellipsoid height minus Swiss sea-level height) in metres. */
export const GEOID_GRID = {
  west: ${WEST},
  south: ${SOUTH},
  step: ${STEP},
  cols: ${COLS},
  rows: ${ROWS},
  /** Row-major, row 0 = south, column 0 = west. */
  values: [
${rows.join('\n')}
  ],
} as const;
`;
writeFileSync(new URL('../../src/geo/geoidGrid.ts', import.meta.url), out);
console.log(
  `wrote ${points.length} points, ${points.filter((p) => p.bessel === undefined).length} extrapolated`,
);
