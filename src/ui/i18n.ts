const MESSAGES: Record<Lang, Record<MessageKey, string>> = { de, en };
const KEY = 'tfs.lang';

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === 'de' || stored === 'en') return stored;
  } catch {
    // Storage blocked: fall through to the browser language.
  }
  return typeof navigator !== 'undefined' && navigator.language.startsWith('de') ? 'de' : 'en';
}

/** Current language; components that call t() re-render when it changes. */
export const lang = signal<Lang>(initialLang());

export function setLang(l: Lang) {
  lang.value = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    // Not critical.
  }
}

/** The text of `key` in the current language; `{name}` placeholders are filled from `params`. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const text = MESSAGES[lang.value][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}

/** A text the app delivers in both languages (lessons), in the current one. */
export function tr(text: { de: string; en: string } | undefined): string {
  return text ? text[lang.value] || text.en || text.de : '';
}

export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(de, key);
}

/** All keys of all languages, for the completeness test. */
export const ALL_MESSAGES = MESSAGES;
